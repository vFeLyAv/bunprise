import { expect, test } from '@playwright/test'

test('demo start preserves all three methods and a separate existing-account entrance', async ({ page }, testInfo) => {
  await page.goto('/?frame=0')
  for (const method of ['google', 'apple', 'email']) {
    const option = page.locator(`a[href*="method=${method}"]`)
    await expect(option).toBeVisible()
    const destination = new URL(await option.getAttribute('href') ?? '', page.url())
    expect(destination.pathname).toBe('/login')
    expect(destination.searchParams.get('mode')).toBe('signup')
  }
  // Selecting an unconfigured provider explains its status without attempting OAuth.
  await expect(page.locator('a[href*="method=google"], a[href*="method=apple"]')).toHaveCount(2)
  const existing = page.locator('a[href*="mode=signin"]')
  await expect(existing).toBeVisible()
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('start-options.png'), fullPage: false, animations: 'disabled' })
  await existing.click()
  await expect(page).toHaveURL(/\/login\?.*mode=signin/)
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await expect(page.locator('a[href*="method=google"], a[href*="method=apple"]')).toHaveCount(2)
  await expect(page.locator('a[href*="method=email"]')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('signin-methods.png'), fullPage: false, animations: 'disabled' })
  await page.locator('a[href*="method=email"]').click()
  await expect(page.getByLabel('E-Mail', { exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox')).toHaveCount(0)
})

test('existing-account email sign-in sends create_user false, stays neutral for an unknown address and preserves its mode', async ({ page }, testInfo) => {
  const requests: unknown[] = []
  page.on('request', (request) => {
    if (request.method() === 'POST' && new URL(request.url()).pathname === '/auth/v1/otp') requests.push(request.postDataJSON())
  })
  await page.goto('/login?mode=signin&method=email&frame=0')
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await page.getByLabel('E-Mail', { exact: true }).fill('unknown-signin@example.test')
  await page.getByRole('button', { name: 'Code schicken', exact: true }).click()
  await expect(page).toHaveURL(/\/login\/code/)
  expect(requests).toHaveLength(1)
  expect(requests[0]).toMatchObject({ email: 'unknown-signin@example.test', create_user: false })
  await expect(page.getByText('Wenn für diese Adresse ein Konto besteht, ist der Code unterwegs.', { exact: true })).toBeVisible()
  await page.getByLabel('Sechsstelliger Code', { exact: true }).fill('123456')
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page).toHaveURL(/\/login\/code/)
  expect(await page.evaluate(() => localStorage.getItem('bunprise.demo.auth'))).toBeNull()
  await page.getByRole('link', { name: 'Andere E-Mail-Adresse', exact: true }).click()
  await expect(page).toHaveURL(/\/login\?.*mode=signin/)
  await expect(page.getByLabel('E-Mail', { exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('existing-signin.png'), fullPage: true, animations: 'disabled' })
})

test('unavailable Apple signup explains the fallback and never simulates provider authentication', async ({ page }, testInfo) => {
  const providerRequests: string[] = []
  page.on('request', (request) => {
    if (new URL(request.url()).pathname === '/auth/v1/authorize') providerRequests.push(request.url())
  })
  await page.goto('/login?mode=signup&method=apple&frame=0')
  // An unavailable method cannot record declarations or authenticate anyone.
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await expect(page.getByText('Mit Apple kannst du dich hier noch nicht anmelden. Nutze vorerst deine E-Mail-Adresse.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Apple/ })).toBeDisabled()
  const fallback = page.locator('a[href*="method=email"]')
  await expect(fallback).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('apple-unavailable.png'), fullPage: true, animations: 'disabled' })
  await fallback.click()
  await expect(page.getByLabel('E-Mail', { exact: true })).toBeVisible()
  expect(providerRequests).toEqual([])
  expect(await page.evaluate(() => localStorage.getItem('bunprise.demo.auth'))).toBeNull()
})

test('demo sign-in checks consent, rejects a wrong code and reaches the profile step', async ({ page }, testInfo) => {
  await page.goto('/login?mode=signup&method=email&frame=0')
  await page.getByLabel('E-Mail', { exact: true }).fill('demo@example.test')
  const send = page.getByRole('button', { name: 'Code schicken', exact: true })
  await expect(send).toBeDisabled()
  const checkboxes = page.getByRole('checkbox')
  await expect(checkboxes).toHaveCount(2)
  await checkboxes.nth(0).check()
  await checkboxes.nth(1).check()
  await page.screenshot({ path: testInfo.outputPath('login.png'), fullPage: true, animations: 'disabled' })
  await send.click()
  await expect(page).toHaveURL(/\/login\/code/)
  expect(page.url()).not.toContain('demo%40')
  await expect(page.getByRole('button', { name: /Nochmal in/ })).toBeDisabled()
  const code = page.getByLabel('Sechsstelliger Code', { exact: true })
  await page.screenshot({ path: testInfo.outputPath('code.png'), fullPage: true, animations: 'disabled' })
  await code.fill('000000')
  await expect(page.getByRole('alert')).toBeVisible()
  await code.fill('123456')
  await expect(page).toHaveURL(/\/welcome\/profile\?next=%2Fsoon/)
})

test('legal links preserve the form and an invitation destination survives sign-in', async ({ page }) => {
  await page.goto('/login?mode=signup&method=email&next=%2Fi&frame=0')
  await page.getByLabel('E-Mail', { exact: true }).fill('friend@example.test')
  await page.getByRole('checkbox').nth(0).check()
  await page.getByRole('checkbox').nth(1).check()
  await page.getByRole('link', { name: 'Nutzungsbedingungen für den Pilotbetrieb' }).click()
  await page.goBack()
  await expect(page.getByLabel('E-Mail', { exact: true })).toHaveValue('friend@example.test')
  await expect(page.getByRole('checkbox').nth(0)).toBeChecked()
  await expect(page.getByRole('checkbox').nth(1)).toBeChecked()
  await page.getByRole('button', { name: 'Code schicken', exact: true }).click()
  await page.getByLabel('Sechsstelliger Code', { exact: true }).fill('123456')
  await expect(page).toHaveURL(/\/welcome\/profile\?next=%2Fi/)
})
