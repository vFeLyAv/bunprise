import { expect, test } from '@playwright/test'

test('create menu survives fast close/reopen, short screens and reduced motion', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/login?mode=signup&method=email&frame=0')
  await page.getByLabel('E-Mail', { exact: true }).fill('animation-check@example.test')
  await page.getByRole('checkbox').nth(0).check()
  await page.getByRole('checkbox').nth(1).check()
  await page.getByRole('button', { name: 'Code schicken', exact: true }).click()
  await page.getByLabel('Sechsstelliger Code', { exact: true }).fill('123456')
  await page.getByLabel('Name', { exact: true }).fill('Mila')
  await page.getByRole('button', { name: 'Fertig', exact: true }).click()
  await page.getByRole('button', { name: 'Überspringen', exact: true }).click()
  const plus = page.getByRole('button', { name: 'Neu erstellen', exact: true })
  await plus.click()
  await page.getByRole('button', { name: /Wunsch hinzufügen/ }).click()
  await page.getByRole('button', { name: '„Meine Wünsche“ anlegen', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.waitForTimeout(60) // deliberately reopen during the exit, not after it
  await plus.click()
  await expect(page.getByRole('dialog', { name: 'Was möchtest du erstellen?' })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await expect(page.getByRole('button', { name: '„Meine Wünsche“ anlegen', exact: true })).toHaveCount(0)

  // A landscape/keyboard-sized viewport must retain reachable actions and no cut-off decoration.
  await page.setViewportSize({ width: 390, height: 320 })
  const newList = page.getByRole('button', { name: 'Neue Wunschliste', exact: true })
  await newList.scrollIntoViewIfNeeded()
  const action = await newList.boundingBox()
  expect(action).not.toBeNull()
  expect(action!.y).toBeGreaterThanOrEqual(0)
  expect(action!.y + action!.height).toBeLessThanOrEqual(320)
  await expect(page.locator('.cm-bunny')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)

  await page.setViewportSize({ width: 320, height: 640 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await plus.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.locator('.cm-bunny')).toHaveCount(0)
  await expect(page.locator('.cm-action').first()).toHaveCSS('transform', 'none')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
