import { expect, test, type Page } from '@playwright/test'

async function signUp(page: Page) {
  await page.goto('/login?mode=signup&method=email&frame=0')
  await page.getByLabel('E-Mail', { exact: true }).fill('shell-a@example.test')
  await page.getByRole('checkbox').nth(0).check()
  await page.getByRole('checkbox').nth(1).check()
  await page.getByRole('button', { name: 'Code schicken', exact: true }).click()
  await page.getByLabel('Sechsstelliger Code', { exact: true }).fill('123456')
  await page.getByLabel('Name', { exact: true }).fill('Mila Demo')
  await page.getByRole('button', { name: 'Fertig', exact: true }).click()
  await page.getByRole('button', { name: 'Weiter', exact: true }).click()
  await page.getByRole('button', { name: 'Überspringen', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Start', exact: true })).toBeVisible()
}

test('Start, first steps, cached dot, toast and keyboard at 420 and 320 pixels', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const shot = async (name: string) => page.screenshot({ path: info.outputPath(name + '.png'), fullPage: true })
  await page.goto('/login?mode=signup&method=email&frame=0')
  await expect(page.getByRole('checkbox').first()).toBeVisible()
  await shot('A11-signup-checkboxes-420')
  await page.setViewportSize({ width: 320, height: 844 })
  await expect(page.getByRole('checkbox').first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const footer = page.getByRole('navigation', { name: 'Rechtliches' })
  for (const link of await footer.getByRole('link').all()) expect((await link.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await shot('A12-footer-320')
  await page.setViewportSize({ width: 420, height: 910 })
  await signUp(page)
  await expect(page.getByRole('heading', { name: 'Erste Schritte', exact: true })).toBeVisible()
  await shot('A4-invited-420')
  const tabbar = page.getByRole('navigation', { name: 'Hauptnavigation' })
  await tabbar.getByRole('link', { name: 'Start', exact: true }).focus()
  for (const name of ['Listen', 'Neu erstellen', 'Ideen', 'Profil']) {
    await page.keyboard.press('Tab')
    await expect(tabbar.getByRole(name === 'Neu erstellen' ? 'button' : 'link', { name: name === 'Listen' ? /^Listen/ : name, exact: true })).toBeFocused()
  }
  await shot('A9-tab-focus-420')
  const radios = page.getByRole('radiogroup', { name: 'Ansicht' }).getByRole('radio')
  for (const radio of await radios.all()) expect((await radio.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await page.evaluate(async () => {
    const { queryClient } = await import('/src/lib/query.ts')
    queryClient.setQueryData(['me'], (me) => ({ ...me, inbox: { follow_requests: 3 } }))
  })
  await expect(tabbar.getByRole('link', { name: 'Listen, neue Anfragen' })).toBeVisible()
  await shot('A10-tab-dot-420')
  await page.evaluate(async () => { const { toast } = await import('/src/lib/toast.ts'); toast.info('A shell test toast') })
  const toast = page.getByRole('status').filter({ hasText: 'A shell test toast' })
  await expect(toast).toBeVisible()
  await expect.poll(async () => (await tabbar.boundingBox())!.y - ((await toast.boundingBox())!.y + (await toast.boundingBox())!.height)).toBeGreaterThanOrEqual(8)
  await shot('A8-toast-420')
  await toast.hover()
  await expect(toast).toHaveCount(0, { timeout: 5000 })
  await page.evaluate(async () => { const { toast } = await import('/src/lib/toast.ts'); toast.info('A second shell test toast') })
  await tabbar.getByRole('button', { name: 'Neu erstellen' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.evaluate(async () => { const { toast } = await import('/src/lib/toast.ts'); toast.clear() })
  await page.evaluate(async () => {
    const { setMotionPrefs } = await import('/src/motion/level.ts'); setMotionPrefs({ level: 'reduced' })
    const { queryClient } = await import('/src/lib/query.ts'); queryClient.setQueryData(['feed'], { upcoming: [], past: [] })
  })
  await expect(page.getByRole('heading', { name: 'Womit fangen wir an?' })).toBeVisible()
  await shot('A4-empty-weniger-420')
  await page.setViewportSize({ width: 320, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await shot('A4-empty-weniger-320')
  await page.getByRole('button', { name: 'Erste Schritte ausblenden' }).click()
  await expect(page.getByRole('heading', { name: 'Noch nichts geplant' })).toBeVisible()
  await page.evaluate(async () => { const { setMotionPrefs } = await import('/src/motion/level.ts'); setMotionPrefs({ level: 'off' }) })
  expect(await page.locator('section[aria-labelledby]').filter({ has: page.getByRole('heading', { name: 'Noch nichts geplant' }) }).locator('.h-44').count()).toBe(0)
  await shot('A5-empty-aus-320')
  expect(errors).toEqual([])
})

test('new occasion lands with both actions, real wishlist and no-wishes hint', async ({ page }, info) => {
  await signUp(page)
  await page.evaluate(async () => { const { router } = await import('/src/router.tsx'); await router.navigate({ to: '/occasions/new' }) })
  await page.getByLabel('Titel', { exact: true }).fill('Mila feiert')
  await page.getByRole('button', { name: /^Datum/ }).click()
  await page.getByRole('button', { name: 'Morgen', exact: true }).click()
  await page.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(page).toHaveURL(/\/soon\?view=month/)
  // The carry deadline starts when the lazy month screen has mounted, independent of dev-server transforms.
  await page.locator('[data-landing]').waitFor({ state: 'attached' })
  const status = page.getByRole('status').filter({ hasText: 'steht jetzt in deinem Kalender' })
  await expect(status).toBeVisible({ timeout: 2500 })
  await expect(status).toContainText('Juhu, der erste Anlass! Jetzt die Wünsche.')
  await expect(status).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Wünsche eintragen' })).toBeFocused()
  const nav = page.getByRole('navigation', { name: 'Hauptnavigation' })
  const invite = page.getByRole('link', { name: 'Freunde zu „Mila feiert“ einladen' })
  await expect.poll(async () => (await nav.boundingBox())!.y - ((await invite.boundingBox())!.y + (await invite.boundingBox())!.height)).toBeGreaterThanOrEqual(8)
  await page.screenshot({ path: info.outputPath('A7-landing-voll-420.png'), fullPage: true })
  const occasionId = await page.evaluate(async () => {
    const { queryClient } = await import('/src/lib/query.ts')
    const feed = queryClient.getQueryData(['feed'])
    return feed.upcoming.find((row) => row.title === 'Mila feiert').id
  })
  await expect.poll(async () => page.evaluate(async (id) => {
    const { queryClient } = await import('/src/lib/query.ts')
    return Boolean(queryClient.getQueryData(['occasion', id])?.wishlist?.id)
  }, occasionId)).toBe(true)
  await page.getByRole('link', { name: 'Wünsche eintragen' }).click()
  await expect(page.getByRole('heading', { name: 'Neuer Wunsch' })).toBeVisible()
  await expect(page.getByText(/Für „Mila feiert“/)).toBeVisible()
  await page.screenshot({ path: info.outputPath('A6-wish-after-create-420.png'), fullPage: true })
  await page.evaluate(async () => { const { router } = await import('/src/router.tsx'); await router.navigate({ to: '/soon', search: {} }) })
  await expect(page.getByRole('link', { name: 'Mila feiert', exact: true }).getByText('Noch keine Wünsche')).toBeVisible()
  await page.screenshot({ path: info.outputPath('A3-no-wishes-420.png'), fullPage: true })
})

test('320px settings controls and the route error offer named, usable actions', async ({ page }, info) => {
  await signUp(page)
  await page.setViewportSize({ width: 320, height: 844 })
  await page.evaluate(async () => { const { router } = await import('/src/router.tsx'); await router.navigate({ to: '/settings' }) })
  await expect(page.getByRole('heading', { name: 'Profil', exact: true })).toBeVisible()
  for (const radio of await page.getByRole('radio').all()) expect((await radio.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('radio', { name: 'Weniger', exact: true }).click()
  await page.screenshot({ path: info.outputPath('A12-settings-320.png'), fullPage: true })
  await page.evaluate(async () => {
    const { router } = await import('/src/router.tsx')
    router.routesById['/_authed/soon'].update({ loader: () => { throw new Error('Fixture error: never display raw details') } })
    await router.navigate({ to: '/soon' })
  })
  await expect(page.getByRole('button', { name: 'Nochmal versuchen' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Zum Start' })).toBeVisible()
  await expect(page.getByText('Fixture error: never display raw details')).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('A13-error-page-320.png'), fullPage: true })
})
